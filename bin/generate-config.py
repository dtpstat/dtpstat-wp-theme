#!/usr/bin/env python3
"""Compile a project's .env into WordPress PHP constants (never source as shell code)."""

import argparse
import os
from pathlib import Path
import re
import tempfile
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parent.parent
OUTPUT_NAME = 'dtpstat-config.php'
MARKER = '// Generated by dtpstat-wp-theme/bin/generate-config.py; DO NOT EDIT.'
KEYS = (
    'DTP_MAP_URL',
    'DTP_FRONTEND_URL',
    'DTP_CONTACT_TELEGRAM_URL',
    'DTP_CONTACT_TELEGRAM_LABEL',
    'DTP_CONTACT_EMAIL',
    'DTP_SOCIAL_TELEGRAM_URL',
    'DTP_SOCIAL_X_URL',
    'DTP_SOCIAL_INSTAGRAM_URL',
    'DTP_SOCIAL_PATREON_URL',
    'DTP_SOCIAL_BOOSTY_URL',
)
REQUIRED = ('DTP_MAP_URL', 'DTP_FRONTEND_URL')
URL_KEYS = {key for key in KEYS if key.endswith('_URL')}


def read_env(source):
    """Parse simple KEY=VALUE entries; no interpolation, shell or variable expansion."""
    if not source.is_file():
        raise ValueError(f'Не найден .env: {source}')
    result = {}
    for line_num, original in enumerate(source.read_text(encoding='utf-8-sig').splitlines(), 1):
        line = original.strip()
        if not line or line.startswith('#'):
            continue
        match = re.fullmatch(r'([A-Za-z_][A-Za-z_0-9]*)\s*=\s*(.*)', line)
        if not match:
            raise ValueError(f'.env строка {line_num}: требуется KEY=VALUE')
        key, value = match.groups()
        if key not in KEYS:
            raise ValueError(f'.env строка {line_num}: неизвестный ключ {key}')
        if key in result:
            raise ValueError(f'.env строка {line_num}: повторный ключ {key}')
        if len(value) >= 2 and value[0] == value[-1] and value[0] in ("'", '"'):
            value = value[1:-1]
        value = value.strip()
        if any(ord(c) < 32 or ord(c) == 127 for c in value):
            raise ValueError(f'.env строка {line_num}: управляющий символ в {key}')
        result[key] = value

    for key in REQUIRED:
        if not result.get(key):
            raise ValueError(f'.env: обязателен {key}')

    for key in URL_KEYS:
        if not result.get(key):
            continue
        parsed = urlsplit(result[key])
        try:
            valid_port = parsed.port is None or 0 < parsed.port < 65536
        except ValueError:
            valid_port = False
        if (parsed.scheme not in ('https', 'http') or not parsed.hostname
                or parsed.username or parsed.password or parsed.query or parsed.fragment
                or not valid_port or any(c.isspace() for c in result[key])):
            raise ValueError(f'.env: {key} должен быть URL http(s) без credentials/query/fragment')
        result[key] = result[key].rstrip('/')

    email = result.get('DTP_CONTACT_EMAIL', '')
    if email and not re.fullmatch(r'[^@\s]+@[^@\s]+\.[^@\s]+', email):
        raise ValueError('.env: DTP_CONTACT_EMAIL должен содержать email')
    return {key: result.get(key, '') for key in KEYS}


def php_literal(value):
    # PHP single-quoted string: only backslash and apostrophe are escaped.
    return "'" + value.replace('\\', '\\\\').replace("'", "\\'") + "'"


def render(values):
    lines = [
        '<?php',
        MARKER,
        '// Contains public theme endpoints/contacts ONLY. Never put secrets in this file.',
        "defined( 'ABSPATH' ) || exit;",
        '',
    ]
    for key in KEYS:
        lines.extend([
            f"if ( ! defined( '{key}' ) ) {{",
            f"    define( '{key}', {php_literal(values[key])} );",
            '}',
        ])
    return '\n'.join(lines) + '\n'


def validate_destination(dest):
    if not dest.is_absolute() or dest.name != OUTPUT_NAME:
        raise ValueError(f'Выходной файл должен быть абсолютным путём */{OUTPUT_NAME}')
    if dest.is_symlink() or not dest.parent.is_dir() or dest.parent.is_symlink():
        raise ValueError('Путь назначения отсутствует или является символической ссылкой')
    if dest.exists():
        if not dest.is_file() or MARKER not in dest.read_text(encoding='utf-8', errors='replace')[:300]:
            raise ValueError('Существующий файл назначения не сгенерирован этим инструментом')
    if not os.access(dest.parent, os.W_OK | os.X_OK):
        raise ValueError(f'Нет прав на запись в каталог: {dest.parent}')


def write_config(dest, text):
    # No in-place partial rewrite: temp file in destination directory, then atomic replace.
    fd, temporary = tempfile.mkstemp(prefix='.dtpstat-config-', suffix='.tmp', dir=dest.parent)
    try:
        with os.fdopen(fd, 'w', encoding='utf-8') as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(temporary, 0o644)  # Only PUBLIC URLs/contacts are permitted in this config.
        os.replace(temporary, dest)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--env-file', type=Path, default=ROOT / '.env',
                        help='проектный .env (по умолчанию <repo>/.env)')
    parser.add_argument('--output', type=Path, required=True,
                        help='абсолютный путь к WP_CONTENT_DIR/dtpstat-config.php')
    parser.add_argument('--check', action='store_true',
                        help='проверить конфигурацию и каталог назначения без изменений')
    args = parser.parse_args(argv)
    try:
        values = read_env(args.env_file)
        generated = render(values)
        validate_destination(args.output)
        if not args.check:
            write_config(args.output, generated)
        print(('CHECK OK' if args.check else 'GENERATED') + f': {args.output} ({len(values)} keys)')
    except (OSError, UnicodeError, ValueError) as exc:
        parser.exit(1, f'Ошибка конфигурации: {exc}\n')


if __name__ == '__main__':
    main()
